"""Genera DTOs Rust/TypeScript desde contracts/schema.json de forma determinista."""

import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
RUST = ROOT / 'crates/core/src/contracts'
TYPESCRIPT = ROOT / 'src/generated/contracts.ts'
MODULES = ('common', 'catalog', 'campaign', 'transport')
HEADER = '// Generated by tools/contracts/generate.py; edit contracts/schema.json.\n'
PRIMITIVES = {
    'string': {'rs': 'String', 'ts': 'string'},
    'integer': {'rs': 'u32', 'ts': 'number'},
    'number': {'rs': 'f64', 'ts': 'number'},
}


def type_name(node: dict, language: str) -> str:
    if '$ref' in node:
        return node['$ref'].split('/')[-1]
    if 'const' in node and language == 'ts':
        return json.dumps(node['const'])
    if 'anyOf' in node:
        inner = type_name(node['anyOf'][0], language)
        return f'Option<{inner}>' if language == 'rs' else f'{inner} | null'
    if node.get('type') == 'array':
        inner = type_name(node['items'], language)
        return f'Vec<{inner}>' if language == 'rs' else f'{inner}[]'
    return PRIMITIVES[node['type']][language]


def pascal_case(value: str) -> str:
    return ''.join(part.capitalize() for part in value.split('_'))


def rust_definition(name: str, node: dict) -> str:
    derive = '#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n'
    if 'enum' in node:
        variants = [f'    #[serde(rename = "{value}")]\n    {pascal_case(value)},'
                    for value in node['enum']]
        return derive + f'pub enum {name} {{\n' + '\n'.join(variants) + '\n}\n'
    if node.get('type') != 'object':
        return f'pub type {name} = {type_name(node, "rs")};\n'
    fields = []
    for field, definition in node['properties'].items():
        if 'anyOf' in definition:
            fields.append('    #[serde(deserialize_with = "super::required_nullable")]')
        fields.append(f'    pub {field}: {type_name(definition, "rs")},')
    strict = '#[serde(deny_unknown_fields)]\n'
    return derive + strict + f'pub struct {name} {{\n' + '\n'.join(fields) + '\n}\n'


def ts_definition(name: str, node: dict) -> str:
    if 'enum' in node:
        choices = ' | '.join(json.dumps(value) for value in node['enum'])
        return f'export type {name} = {choices};\n'
    if node.get('type') != 'object':
        return f'export type {name} = {type_name(node, "ts")};\n'
    fields = [f'  {field}: {type_name(value, "ts")};'
              for field, value in node['properties'].items()]
    return f'export interface {name} {{\n' + '\n'.join(fields) + '\n}\n'


def rust_module(module: str, definitions: dict) -> str:
    # Unused cross-module imports are omitted rather than silencing compiler warnings.
    needed = {'common': [], 'catalog': ['common'], 'campaign': ['common'],
              'transport': ['common', 'catalog', 'campaign']}[module]
    imports = [f'use super::{other}::*;' for other in needed]
    body = [rust_definition(name, node) for name, node in definitions.items()
            if node['x-module'] == module]
    source = HEADER + '\n'.join(imports) + '\n\n' + '\n'.join(body)
    result = subprocess.run(['rustfmt', '--edition', '2024'], input=source,
                            text=True, capture_output=True, check=True)
    return result.stdout


def artifacts(definitions: dict) -> dict[Path, str]:
    outputs = {RUST / f'{module}.rs': rust_module(module, definitions) for module in MODULES}
    outputs[TYPESCRIPT] = HEADER + '\n' + '\n'.join(
        ts_definition(name, node) for name, node in definitions.items())
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated files drift')
    args = parser.parse_args()
    schema = json.loads((ROOT / 'contracts/schema.json').read_text())
    for path, content in artifacts(schema['$defs']).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated contract: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
