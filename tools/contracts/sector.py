"""desire.sector-render/1 from contracts/sector-render.json: check the layout, encode and decode
payloads, validate them, and generate the Rust and TypeScript layout constants and the fixture.

    python3 tools/contracts/sector.py            # write generated files
    python3 tools/contracts/sector.py --check    # fail if they drift
    python3 tools/contracts/sector.py --validate outputs/.../sectors/*.render.bin
"""

import argparse
import json
import math
from pathlib import Path
import struct
import subprocess
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / 'contracts/sector-render.json'
RUST = ROOT / 'crates/core/src/sector/layout.rs'
TYPESCRIPT = ROOT / 'src/generated/sector-layout.ts'
FIXTURE = ROOT / 'crates/core/tests/fixtures/sector-v1.bin'
HEADER_NOTE = 'Generated by tools/contracts/sector.py; edit contracts/sector-render.json.'
# Field type: struct code, size in bytes, natural alignment.
TYPES = {
    'u8': ('B', 1, 1),
    'u16': ('H', 2, 2),
    'u32': ('I', 4, 4),
    'f32': ('f', 4, 4),
    'ascii4': ('4s', 4, 1),
    'rgb8': ('3B', 3, 1),
}
STRUCTURE = ('magic', 'version', 'section_count')
Record = dict[str, Any]


# --- Layout -------------------------------------------------------------------------------

def check_fields(name: str, fields: list[Record], size: int) -> None:
    """Fields lie inside `size`, on their natural alignment, without overlapping."""
    end = 0
    for field in sorted(fields, key=lambda item: item['offset']):
        label = f"{name}.{field['name']}"
        _, width, align = TYPES[field['type']]
        if field['offset'] % align:
            raise ValueError(f'{label}: offset {field["offset"]} not {align}-aligned')
        if field['offset'] < end:
            raise ValueError(f'{label}: overlaps the previous field')
        end = field['offset'] + width
        if end > size:
            raise ValueError(f'{label}: ends at {end}, past {size}')


def check_layout(contract: Record) -> None:
    """Raises ValueError naming the first inconsistent part of the contract."""
    align = contract['alignment']
    check_fields('header', contract['header']['fields'], contract['header']['size'])
    check_fields('entry', contract['section_entry']['fields'], contract['section_entry']['size'])
    kinds = [section['kind'] for section in contract['sections']]
    if kinds != sorted(set(kinds)):
        raise ValueError('sections: kinds must be unique and ascending')
    for section in contract['sections']:
        if section['stride'] % align:
            raise ValueError(f"{section['name']}: stride not {align}-aligned")
        check_fields(section['name'], section['fields'], section['stride'])


# --- Encoding -----------------------------------------------------------------------------

def pack(buffer: bytearray, offset: int, field: Record, value: Any) -> None:
    code = '<' + TYPES[field['type']][0]
    values = value if field['type'] == 'rgb8' else [value]
    if field['type'] == 'ascii4':
        values = [value.encode('ascii')]
    struct.pack_into(code, buffer, offset, *values)


def unpack(data: bytes, offset: int, field: Record) -> Any:
    values = struct.unpack_from('<' + TYPES[field['type']][0], data, offset)
    if field['type'] == 'rgb8':
        return list(values)
    if field['type'] == 'ascii4':
        return values[0].decode('ascii', errors='replace')
    return values[0]


def layout_of(contract: Record, sector: Record) -> list[Record]:
    """Section table entries in kind order, offsets after the header and the table."""
    table = len(contract['sections']) * contract['section_entry']['size']
    offset = contract['header']['size'] + table
    entries = []
    for section in contract['sections']:
        count = len(sector[section['name']])
        entries.append({'kind': section['kind'], 'count': count, 'stride': section['stride'],
                        'offset': offset})
        offset += count * section['stride']
    return entries


def encode(contract: Record, sector: Record) -> bytes:
    entries = layout_of(contract, sector)
    last = entries[-1]
    buffer = bytearray(last['offset'] + last['count'] * last['stride'])
    header = {**sector, 'magic': contract['magic'], 'version': contract['version'],
              'section_count': len(entries)}
    for field in contract['header']['fields']:
        pack(buffer, field['offset'], field, header.get(field['name'], 0))
    entry_size = contract['section_entry']['size']
    for number, entry in enumerate(entries):
        at = contract['header']['size'] + number * entry_size
        for field in contract['section_entry']['fields']:
            pack(buffer, at + field['offset'], field, entry[field['name']])
    for section, entry in zip(contract['sections'], entries):
        for record, values in enumerate(sector[section['name']]):
            at = entry['offset'] + record * entry['stride']
            for field in section['fields']:
                pack(buffer, at + field['offset'], field, values[field['name']])
    return bytes(buffer)


# --- Decoding and validation --------------------------------------------------------------

def read_header(contract: Record, data: bytes) -> Record:
    header_size = contract['header']['size']
    if len(data) < 6:
        raise ValueError('truncated: no magic and version')
    fields = {field['name']: field for field in contract['header']['fields']}
    if unpack(data, 0, fields['magic']) != contract['magic']:
        raise ValueError('magic: not ' + contract['magic'])
    version = unpack(data, fields['version']['offset'], fields['version'])
    if version != contract['version']:
        raise ValueError(f'version: {version} is not {contract["version"]}')
    if len(data) < header_size:
        raise ValueError(f'truncated: {len(data)} bytes, header needs {header_size}')
    return {name: unpack(data, field['offset'], field) for name, field in fields.items()}


def read_entries(contract: Record, data: bytes, count: int) -> list[Record]:
    size = contract['section_entry']['size']
    start = contract['header']['size']
    if len(data) < start + count * size:
        raise ValueError(f'truncated: section table of {count} entries')
    return [{field['name']: unpack(data, start + number * size + field['offset'], field)
             for field in contract['section_entry']['fields']} for number in range(count)]


def check_entry(contract: Record, entry: Record, data_length: int) -> Record | None:
    """The known section an entry describes, after its structural checks, or None."""
    known = {section['kind']: section for section in contract['sections']}.get(entry['kind'])
    label = known['name'] if known else f"kind {entry['kind']}"
    if entry['offset'] % contract['alignment']:
        raise ValueError(f'{label} misaligned at {entry["offset"]}')
    if known and entry['stride'] < known['stride']:
        raise ValueError(f'{label} stride {entry["stride"]} < {known["stride"]}')
    if entry['offset'] + entry['count'] * entry['stride'] > data_length:
        raise ValueError(f'{label} out of bounds')
    return known


def decode(contract: Record, data: bytes) -> Record:
    """The sector as the contract's example spells it. Unknown kinds are skipped."""
    header = read_header(contract, data)
    sector = {name: value for name, value in header.items()
              if name not in STRUCTURE and not name.startswith('reserved')}
    sector.update({section['name']: [] for section in contract['sections']})
    for entry in read_entries(contract, data, header['section_count']):
        section = check_entry(contract, entry, len(data))
        if section is None:
            continue
        for record in range(entry['count']):
            at = entry['offset'] + record * entry['stride']
            sector[section['name']].append(
                {field['name']: unpack(data, at + field['offset'], field)
                 for field in section['fields']})
    return sector


def check_value(label: str, field: Record, value: Any) -> None:
    if field['type'] == 'f32' and not math.isfinite(value):
        raise ValueError(f'{label}: not finite')
    if field.get('positive') and not value > 0:
        raise ValueError(f'{label}: {value} is not positive')
    if field.get('zero') and value != 0:
        raise ValueError(f'{label}: reserved, must be 0')
    if 'bits' in field and value & ~sum(1 << bit for bit in field['bits'].values()):
        raise ValueError(f'{label}: unknown flag bits in {value:#04x}')


def validate_payload(contract: Record, data: bytes) -> Record:
    """Structure and every constraint of the contract. Returns the decoded sector."""
    header = read_header(contract, data)
    for field in contract['header']['fields']:
        check_value(field['name'], field, header[field['name']])
    sector = decode(contract, data)
    for section in contract['sections']:
        for number, record in enumerate(sector[section['name']]):
            for field in section['fields']:
                label = f"{section['name']}[{number}].{field['name']}"
                check_value(label, field, record[field['name']])
    return sector


# --- Generated files ----------------------------------------------------------------------

def constant(name: str) -> str:
    return name.upper()


def constants(contract: Record) -> list[tuple[str, str, int, str]]:
    """(name, Rust type, value, doc) for every layout number the implementations need."""
    rows = [('VERSION', 'u16', contract['version'], 'Major version this layout describes.'),
            ('ALIGNMENT', 'usize', contract['alignment'], 'Every section starts on a multiple.'),
            ('HEADER_BYTES', 'usize', contract['header']['size'], ''),
            ('ENTRY_BYTES', 'usize', contract['section_entry']['size'], '')]
    for field in contract['header']['fields']:
        rows.append((f"HEADER_{constant(field['name'])}", 'usize', field['offset'],
                     field.get('doc', '')))
    for field in contract['section_entry']['fields']:
        rows.append((f"ENTRY_{constant(field['name'])}", 'usize', field['offset'], ''))
    for section in contract['sections']:
        prefix = constant(section['name'])
        rows.append((f'{prefix}_KIND', 'u32', section['kind'], ''))
        rows.append((f'{prefix}_STRIDE', 'usize', section['stride'], ''))
        for field in section['fields']:
            rows.append((f"{prefix}_{constant(field['name'])}", 'usize', field['offset'],
                         field.get('doc', '')))
            for bit_name, bit in field.get('bits', {}).items():
                rows.append((f'{prefix}_{constant(bit_name)}_BIT', 'u8', 1 << bit, ''))
    return rows


def rust_source(contract: Record) -> str:
    lines = [f'// {HEADER_NOTE}', f'//! Byte layout of `{contract["$id"]}`: offsets in bytes.', '',
             f'pub const MAGIC: &[u8; 4] = b"{contract["magic"]}";']
    for name, kind, value, doc in constants(contract):
        if doc:
            lines.append(f'/// {doc}')
        lines.append(f'pub const {name}: {kind} = {value};')
    result = subprocess.run(['rustfmt', '--edition', '2024'], input='\n'.join(lines) + '\n',
                            text=True, capture_output=True, check=True)
    return result.stdout


def typescript_source(contract: Record) -> str:
    lines = [f'// {HEADER_NOTE}', f'// Byte layout of `{contract["$id"]}`: offsets in bytes.', '',
             f"export const MAGIC = '{contract['magic']}';"]
    for name, _, value, doc in constants(contract):
        if doc:
            lines.append(f'/** {doc} */')
        lines.append(f'export const {name} = {value};')
    return '\n'.join(lines) + '\n'


def artifacts(contract: Record) -> dict[Path, str | bytes]:
    check_layout(contract)
    return {RUST: rust_source(contract), TYPESCRIPT: typescript_source(contract),
            FIXTURE: encode(contract, contract['example'])}


def write_or_check(contract: Record, check: bool) -> None:
    for path, content in artifacts(contract).items():
        current = None
        if path.exists():
            current = path.read_bytes() if isinstance(content, bytes) else path.read_text()
        if check and current != content:
            raise SystemExit(f'Stale generated sector contract: {path.relative_to(ROOT)}')
        if not check and current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, bytes):
                path.write_bytes(content)
            else:
                path.write_text(content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if generated files drift')
    parser.add_argument('--validate', nargs='+', type=Path, metavar='PAYLOAD',
                        help='validate sector payloads against the contract')
    args = parser.parse_args()
    contract = json.loads(CONTRACT.read_text())
    if not args.validate:
        write_or_check(contract, args.check)
        return
    for path in args.validate:
        try:
            sector = validate_payload(contract, path.read_bytes())
        except ValueError as error:
            raise SystemExit(f'{path}: {error}') from error
        counts = ', '.join(f"{len(sector[s['name']])} {s['name']}" for s in contract['sections'])
        print(f'{path}: ok ({counts})')


if __name__ == '__main__':
    main()
